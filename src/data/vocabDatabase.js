/**
 * Returns words in a given category (or list ID like 'swadesh-100').
 * @param {string} categoryId
 * @returns {Array}
 */
export function getWordsByCategory(categoryId) {
    if (!categoryId || categoryId === 'all') return vocabDatabase;
    const listIds = ['swadesh-100', 'swadesh-207', 'leipzig-jakarta'];
    if (listIds.includes(categoryId)) {
        return vocabDatabase.filter(w => Array.isArray(w.lists) && w.lists.includes(categoryId));
    }
    return vocabDatabase.filter(w => w.category === categoryId);
}

/**
 * Returns the total count of words in a category.
 * @param {string} categoryId
 * @returns {number}
 */
export function getCategoryTotal(categoryId) {
    return getWordsByCategory(categoryId).length;
}
