/**
 * Filter words by list and/or semantic theme.
 * @param {string} listId - e.g. 'all', 'phrase-builder', 'core-500', 'swadesh-207'
 * @param {string} categoryId - e.g. 'all', 'actions-verbs', 'nature'
 * @returns {Array}
 */
export function getWords(listId = 'all', categoryId = 'all') {
    return vocabDatabase.filter(w => {
        if (listId && listId !== 'all') {
            if (!Array.isArray(w.lists) || !w.lists.includes(listId)) return false;
        }
        if (categoryId && categoryId !== 'all') {
            if (w.category !== categoryId) return false;
        }
        return true;
    });
}

/**
 * Returns words in a given category or list ID.
 * Supports legacy single-argument calls (e.g. getWordsByCategory('swadesh-100') or getWordsByCategory('nature'))
 * as well as two-argument calls (categoryId, listId).
 * @param {string} categoryId
 * @param {string} [listId='all']
 * @returns {Array}
 */
export function getWordsByCategory(categoryId, listId = 'all') {
    if (!categoryId || categoryId === 'all') {
        if (!listId || listId === 'all') return vocabDatabase;
        return getWords(listId, 'all');
    }
    const listIds = ['swadesh-100', 'swadesh-207', 'leipzig-jakarta', 'phrase-builder', 'core-500', 'core-1000'];
    if (listIds.includes(categoryId)) {
        return vocabDatabase.filter(w => Array.isArray(w.lists) && w.lists.includes(categoryId));
    }
    return getWords(listId, categoryId);
}

/**
 * Returns the total count of words in a category or list.
 * @param {string} categoryId
 * @param {string} [listId='all']
 * @returns {number}
 */
export function getCategoryTotal(categoryId, listId = 'all') {
    return getWordsByCategory(categoryId, listId).length;
}
